#!/usr/bin/env python3
"""Generate the on-board regression vectors for the EDGE ZYNQ (xc7z010) run.

Writes dlzs_vectors.h: signed 16-bit operand pairs plus the expected product
from the golden model. The pairs are exactly the set the cocotb benches use
(sweep.sampled_pairs: fixed seed + full corner cross product), interpreted as
two's complement, so board, simulation and published tables share one set.

    python board/edge_zynq/gen_vectors.py                  # dlzs_opt (deployed IP)
    python board/edge_zynq/gen_vectors.py --design comp    # dlzs_comp_three
    python board/edge_zynq/gen_vectors.py --n-random 20000
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "src"))

from golden_model import SIGNED_DESIGNS, to_signed  # noqa: E402
from sweep import SEED, sampled_pairs  # noqa: E402

MODELS = {
    "opt": "dlzs_nearest_linear",   # dlzc_opt_top, what the AXI IP wraps today
    "comp": "dlzs_three_level",     # dlzc_comp_top
}
W = 16


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--design", choices=MODELS, default="opt")
    ap.add_argument("--n-random", type=int, default=10000)
    ap.add_argument("--out", default=os.path.join(HERE, "dlzs_vectors.h"))
    args = ap.parse_args()

    model_name = MODELS[args.design]
    model = SIGNED_DESIGNS[model_name]
    raw, n_corner = sampled_pairs(W, args.n_random)
    pairs = [(to_signed(a, W), to_signed(b, W)) for a, b in raw]

    lines = [
        "/* Generated by board/edge_zynq/gen_vectors.py -- do not edit. */",
        "#ifndef DLZS_VECTORS_H",
        "#define DLZS_VECTORS_H",
        "#include <stdint.h>",
        "",
        f'#define DLZS_VEC_MODEL    "{model_name}"',
        f"#define DLZS_VEC_SEED     {SEED}",
        f"#define DLZS_VEC_N_CORNER {n_corner}",
        f"#define DLZS_VEC_N_RANDOM {args.n_random}",
        f"#define DLZS_VEC_COUNT    {len(pairs)}",
        "",
        "typedef struct { int16_t a; int16_t b; int32_t p; } dlzs_vec_t;",
        "",
        "static const dlzs_vec_t dlzs_vectors[DLZS_VEC_COUNT] = {",
    ]
    for a, b in pairs:
        p = model(a, b, W)
        assert -(1 << 31) <= p < (1 << 31), (a, b, p)
        lines.append(f"    {{{a}, {b}, {p}}},")
    lines += ["};", "", "#endif", ""]

    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"{args.out}: {len(pairs)} vectors "
          f"({n_corner} corner + {args.n_random} random), model {model_name}")


if __name__ == "__main__":
    main()
